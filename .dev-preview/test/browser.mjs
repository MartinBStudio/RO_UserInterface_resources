import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { PNG } from 'pngjs';
import { createPreviewServer } from '../server.mjs';

const server = createPreviewServer({watch:true});
await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
  const page = await browser.newPage({viewport:{width:1440,height:1000}});
  const errors = []; page.on('pageerror',e => errors.push(e.message));
  await page.goto(origin);
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready'),{timeout:60000});
  assert.match(await page.locator('#heading').textContent(),/Arua/);
  await page.locator('#source-toggle').click();
  console.log('Initial diagnostics:',await page.locator('#diagnostics').textContent());
  const canvas = page.frameLocator('#preview').locator('#canvas');
  const frameSource = await page.locator('#preview').getAttribute('src');
  await page.locator('#resolution').selectOption('1920x1080');
  await canvas.waitFor();
  await page.waitForFunction(() => document.querySelector('#preview').contentDocument.querySelector('canvas').dataset.viewport === '1920x1080');
  assert.equal(await canvas.getAttribute('width'),'1920');
  assert.equal(await canvas.getAttribute('height'),'1080');
  const fitted = await page.locator('#preview').boundingBox();
  assert.ok(fitted.width < 1920,'Fit view shrinks the display without shrinking its render resolution');
  await page.locator('#scale').selectOption('1.5');
  await page.waitForFunction(() => document.querySelector('#preview').contentDocument.querySelector('canvas').dataset.uiScale === '1.5');
  assert.equal(await canvas.getAttribute('width'),'1920','UI scale preserves screen resolution');
  assert.equal(await page.locator('#preview').getAttribute('src'),frameSource,'Display changes preserve the loaded document');
  await page.locator('#resolution').selectOption('3840x2160');
  await page.waitForFunction(() => document.querySelector('#preview').contentDocument.querySelector('canvas').width === 3840);
  await page.locator('#view').selectOption('actual');
  assert.equal(Math.round((await page.locator('#preview').boundingBox()).width),3840);
  assert.ok(await page.locator('#viewport-scroll').evaluate(el => el.scrollWidth > el.clientWidth),'Actual pixels view scrolls');
  await page.locator('#resolution').selectOption('custom');
  await page.locator('#viewport-width').fill('1440'); await page.locator('#viewport-width').dispatchEvent('change');
  await page.locator('#viewport-height').fill('900'); await page.locator('#viewport-height').dispatchEvent('change');
  await page.locator('#scale').selectOption('custom');
  await page.locator('#scale-percent').fill('135'); await page.locator('#scale-percent').dispatchEvent('change');
  await page.waitForFunction(() => {
    const c = document.querySelector('#preview').contentDocument.querySelector('canvas');
    return c.dataset.viewport === '1440x900' && c.dataset.uiScale === '1.35';
  });
  await page.reload();
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready'));
  assert.equal(await page.locator('#resolution').inputValue(),'custom');
  assert.equal(await page.locator('#scale-percent').inputValue(),'135');
  assert.equal(await canvas.getAttribute('width'),'1440');
  await page.locator('#resolution').selectOption('auto');
  await page.locator('#scale').selectOption('1');
  await page.locator('#view').selectOption('fit');
  const inventory = PNG.sync.read(await canvas.screenshot({path:'test-results/arua-inventory.png'}));
  let bright = 0;
  for (let i = 0; i < inventory.data.length; i += 4) if (inventory.data[i] > 120 && inventory.data[i+1] > 120) bright++;
  assert.ok(bright > 10000,'The theme artwork must actually be rendered, not just an empty canvas');
  await page.locator('#window').selectOption('/data/ui/themes/rose/game/hud.html');
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready'));
  const normalHud = await canvas.screenshot({path:'test-results/arua-hud.png'});
  await page.locator('#preset').selectOption('low-health');
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready'));
  const lowHealth = await page.request.get(origin+'/api/asset?theme=Arua&path=/data/ui/themes/rose/game/hud.html&preset=low-health');
  assert.match(await lowHealth.text(),/value="560"/);
  const lowHud = await canvas.screenshot({path:'test-results/arua-hud-low.png'});
  assert.notDeepEqual(normalHud,lowHud,'Changing sample health must change the rendered gauges');
  await page.locator('#theme').selectOption('Ancient');
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready'));
  assert.match(await page.locator('#heading').textContent(),/Ancient/);
  await canvas.screenshot({path:'test-results/ancient-hud.png'});
  await page.locator('#window').selectOption('/data/ui/themes/rose/game/party.html');
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready'));
  await canvas.screenshot({path:'test-results/ancient-party.png'});
  const beforeInspector = await canvas.screenshot();
  await page.locator('#debug').click();
  await page.waitForTimeout(300);
  const inspector = await canvas.screenshot({path:'test-results/inspector.png'});
  assert.notDeepEqual(beforeInspector,inspector,'The real RmlUi inspector must appear');
  await page.locator('#debug').click();
  // Touching the fixture file exercises filesystem watch -> SSE -> iframe reload.
  const fixture = new URL('../mock-data.json',import.meta.url);
  const original = fs.statSync(fixture);
  const request = page.waitForRequest(r => r.url().includes('/preview.html?'));
  fs.utimesSync(fixture,new Date(),new Date());
  await request;
  fs.utimesSync(fixture,original.atime,original.mtime);
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready'));
  await page.screenshot({path:'test-results/workshop.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Browser passed: WASM rendering, resolutions through 4K, fit/actual pixels, custom dimensions/scales, persisted display settings, theme/window/state switching, inspector, and live reload.');
} finally { await browser.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); }
