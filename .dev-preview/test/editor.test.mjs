import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createPreviewServer, findBase } from '../server.mjs';
import { editorFixture } from './editor-fixture.mjs';
import { load } from 'cheerio';

test('editor drafts are isolated, save theme overrides, protect external changes, and restrict writes',async t => {
  const fixture = editorFixture(); t.after(() => fixture.cleanup());
  const server = createPreviewServer({resourceRoot:fixture.resourceRoot,base:findBase(),watch:false});
  await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
  t.after(() => new Promise(resolve => { server.closeAllConnections(); server.close(resolve); }));
  const origin = `http://127.0.0.1:${server.address().port}`;
  const {editToken} = await (await fetch(origin+'/api/catalog')).json();
  const params = requested => new URLSearchParams({theme:fixture.theme,path:requested});
  const read = async requested => (await fetch(origin+'/api/source?'+params(requested))).json();
  const post = (endpoint,values,headers = {}) => fetch(origin+'/api/editor/'+endpoint,{method:'POST',headers:{'Content-Type':'application/json','Origin':origin,'X-Preview-Token':editToken,...headers},body:JSON.stringify({theme:fixture.theme,path:fixture.window,draft:'session-one',...values})});
  const files = await (await fetch(origin+'/api/editor/files?'+params(fixture.window))).json();
  assert.ok(files.some(f => f.path === fixture.css));
  const initial = await read(fixture.window);
  const edited = fixture.source.replace('Original preview text','Edited text žluťoučký');
  assert.equal((await post('draft',{source:edited})).status,200);
  const preview = '/api/asset?'+params(fixture.window);
  assert.match(load(await (await fetch(origin+preview+'&draft=session-one')).text(),{xmlMode:true})('#message').text(),/Edited text žluťoučký/);
  assert.doesNotMatch(await (await fetch(origin+preview+'&draft=session-two')).text(),/Edited text/);
  assert.equal(fs.readFileSync(path.join(fixture.dir,fixture.window),'utf8'),fixture.source);
  assert.equal((await post('save',{source:edited,version:initial.version})).status,200);
  assert.equal(fs.readFileSync(path.join(fixture.dir,fixture.window),'utf8'),edited);
  assert.equal((await post('save',{source:'stale',version:initial.version})).status,409);
  assert.equal(fs.readFileSync(path.join(fixture.dir,fixture.window),'utf8'),edited);
  assert.equal((await post('draft',{source:fixture.source})).status,200);
  assert.equal((await post('draft',{source:null})).status,200);
  assert.match(await (await fetch(origin+preview+'&draft=session-one')).text(),/Edited text/);
  const fallback = '/data/ui/themes/rose/templates/window-box.html', base = await read(fallback);
  const before = fs.readFileSync(base.file,'utf8');
  assert.equal((await post('save',{path:fallback,source:before+'\n<!-- theme override -->',version:base.version})).status,200);
  assert.equal(fs.readFileSync(base.file,'utf8'),before,'The base file is unchanged');
  assert.match(fs.readFileSync(path.join(fixture.dir,fallback),'utf8'),/theme override/);
  assert.match(fs.readFileSync(path.join(fixture.dir,'.pack/FILE_LIST.txt'),'utf8'),/templates\\window-box.html/);
  assert.equal((await post('save',{path:'/data/ui/themes/rose/../../manifest.json',source:'bad',version:base.version})).status,400);
  assert.equal((await post('save',{path:'/data/ui/themes/rose/game/code.js',source:'bad'})).status,400);
  assert.equal((await post('draft',{source:'bad'},{Origin:'https://elsewhere.example'})).status,403);
  assert.equal((await post('draft',{source:'bad'},{'X-Preview-Token':'wrong'})).status,403);
});
