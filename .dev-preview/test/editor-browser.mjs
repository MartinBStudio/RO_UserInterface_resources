import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { createPreviewServer, findBase } from '../server.mjs';
import { editorFixture } from './editor-fixture.mjs';

const fixture = editorFixture();
const server = createPreviewServer({resourceRoot:fixture.resourceRoot,base:findBase(),watch:false});
await new Promise(resolve => server.listen(0,'127.0.0.1',resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({channel:'chrome',headless:true,args:['--enable-webgl','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
try {
  const page = await browser.newPage({viewport:{width:1700,height:1100}});
  const errors = []; page.on('pageerror',error => errors.push(error.message));
  await page.goto(origin);
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready') && !document.getElementById('code-editor').disabled);
  await page.locator('#window').selectOption(fixture.window);
  await page.waitForFunction(() => document.getElementById('status').textContent.startsWith('Ready') && document.getElementById('code-editor').value.includes('Original preview text'));
  const editor = page.locator('#code-editor'), canvas = page.frameLocator('#preview').locator('#canvas');
  assert.equal(await editor.inputValue(),fixture.source);
  const frameSource = await page.locator('#preview').getAttribute('src');
  const before = await canvas.screenshot();
  const edited = fixture.source.replace('Original preview text','Instant live code preview');
  await editor.fill(edited);
  await page.waitForFunction(() => document.getElementById('editor-status').textContent.includes('Preview updated'));
  assert.equal(await page.locator('#preview').getAttribute('src'),frameSource,'Typing does not reload the iframe');
  const after = await canvas.screenshot();
  assert.notDeepEqual(before,after,'Typing changes actual rendered pixels');
  assert.equal(fs.readFileSync(path.join(fixture.dir,fixture.window),'utf8'),fixture.source,'Typing does not change disk files');
  await page.locator('#editor-save').click();
  await page.waitForFunction(() => document.getElementById('editor-status').textContent.startsWith('Saved to'));
  assert.equal(fs.readFileSync(path.join(fixture.dir,fixture.window),'utf8'),edited);
  await page.locator('#editor-file').selectOption(fixture.css);
  await page.waitForFunction(() => document.getElementById('code-editor').value.includes('background-color'));
  await editor.fill(fixture.stylesheet.replace('rgb(20, 40, 60)','rgb(180, 20, 60)'));
  await page.waitForFunction(() => document.getElementById('editor-status').textContent.includes('Preview updated'));
  const cssPreview = await canvas.screenshot();
  assert.notDeepEqual(after,cssPreview,'Linked stylesheet drafts update actual rendered pixels');
  await page.locator('#editor-discard').click();
  await page.waitForFunction(() => document.getElementById('code-editor').value === document.getElementById('code-editor').defaultValue || document.getElementById('editor-dirty').textContent === 'All changes saved');
  assert.equal(await editor.inputValue(),fixture.stylesheet);
  const current = await editor.inputValue();
  fs.writeFileSync(path.join(fixture.dir,fixture.css),current+'\n/* external edit */');
  await editor.fill(current+'\n/* browser edit */');
  await page.waitForFunction(() => document.getElementById('editor-status').textContent.includes('Preview updated'));
  await page.locator('#editor-save').click();
  await page.waitForFunction(() => document.getElementById('editor-status').textContent.includes('changed on disk'));
  assert.match(fs.readFileSync(path.join(fixture.dir,fixture.css),'utf8'),/external edit/);
  await page.locator('#editor-discard').click();
  await page.waitForFunction(() => document.getElementById('editor-dirty').textContent === 'All changes saved');
  const originalWidth = (await page.locator('.preview-pane').boundingBox()).width;
  await page.locator('#splitter').focus(); await page.keyboard.press('ArrowRight');
  assert.ok((await page.locator('.preview-pane').boundingBox()).width > originalWidth);
  await page.locator('#editor-toggle').click(); assert.equal(await page.locator('#editor-pane').isVisible(),false);
  await page.locator('#editor-toggle').click();
  await page.screenshot({path:'test-results/live-editor.png',fullPage:true});
  assert.deepEqual(errors,[]);
  console.log('Editor browser passed: live HTML/CSS rendering, explicit save, discard, conflict protection, pane resizing, and hide/show.');
} finally {
  await browser.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); fixture.cleanup();
}
